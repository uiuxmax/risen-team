#!/usr/bin/env node
// Keep browser assets and the self-contained export logo tied to the supplied SVGs.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
for (const name of ["logo-full.svg", "logo-sign.svg"]) {
  fs.copyFileSync(path.join(root, "assets", name), path.join(root, "public", name));
}
const svg = fs.readFileSync(path.join(root, "assets/logo-full.svg"));
const output = path.join(root, "src/lib/branding");
fs.mkdirSync(output, { recursive: true });
fs.writeFileSync(path.join(output, "default-logo.ts"),
  `// Generated by scripts/generate-brand-assets.mjs from assets/logo-full.svg.\n` +
  `export const DEFAULT_LOGO_DATA_URL = ${JSON.stringify(`data:image/svg+xml;base64,${svg.toString("base64")}`)};\n`);
